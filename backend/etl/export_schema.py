import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config


OUT = os.path.join(os.path.dirname(config.DB), "schema.sql")


def main():
    if not os.path.exists(config.DB):
        sys.exit("Database not found. Run `python backend/etl/clean.py` first.")

    conn = sqlite3.connect(config.DB)
    try:
            objects = conn.execute(
                "SELECT type, name, sql FROM sqlite_master "
                "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
                "ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name"
            ).fetchall()
            lookups = {
                "payment_types": conn.execute("SELECT * FROM payment_types ORDER BY 1").fetchall(),
                "rate_codes": conn.execute("SELECT * FROM rate_codes ORDER BY 1").fetchall(),
                }
            counts = {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
                      for t, in conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
    finally:
            conn.close()

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("-- NYC Taxi Urban Mobility Explorer: database schema (SQLite)\n")
        f.write("--Generated by backend/etl/export_schema.py\n")
        f.write("--Row counts when exported: " + ", ".join(f"{t}={n:,}"for t, n in sorted(counts.items())) + "\n\n")
        for kind, name, sql in objects:
            f.write(f"-- {kind}: {name}\n{sql};\n\n")
        f.write("-- Lookup data (small tables, included in full)\n")
        for table, rows in lookups.items():
            for row in rows:
                values = ", ".join(repr(v) if isinstance(v, str) else str(v) for v in row)
                f.write(f"INSERT INTO {table} VALUES ({values});\n")
    print(f"Schema written -> {OUT}")


if __name__ == "__main__":
     main()

            